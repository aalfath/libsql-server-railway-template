#!/bin/bash
# Railway start script for libSQL Server (sqld).
# Sets safe defaults, turns authentication on, then hands over to the image's own wrapper.
set -Eeuo pipefail

# Data lives on the Railway volume mounted at /var/lib/sqld.
# "standalone" serves everything (HTTP, WebSocket, embedded-replica sync) on the one
# authenticated HTTP port. "primary" also opens sqld's internal gRPC port 5001 for
# sqld read replicas; that port doesn't check client auth, so it's opt-in.
export SQLD_NODE="${SQLD_NODE:-standalone}"
export SQLD_DB_PATH="${SQLD_DB_PATH:-/var/lib/sqld/iku.db}"

# Listen on Railway's PORT. Use [::] (IPv4 and IPv6) so the private network works too.
if [ -z "${SQLD_HTTP_LISTEN_ADDR:-}" ]; then
  if [ -e /proc/net/if_inet6 ]; then
    export SQLD_HTTP_LISTEN_ADDR="[::]:${PORT:-8080}"
  else
    export SQLD_HTTP_LISTEN_ADDR="0.0.0.0:${PORT:-8080}"
  fi
fi

# Authentication. Never start an open database on a public URL by accident.
#  - SQLD_AUTH_JWT_KEY / SQLD_AUTH_JWT_KEY_FILE set: sqld uses JWT (Ed25519) auth.
#  - otherwise SQLD_AUTH_TOKEN (generated by the template): clients send it as
#    "Authorization: Bearer <token>", which is what libSQL clients do with authToken.
#  - SQLD_ALLOW_NO_AUTH=true: run without auth (only for a service with no public domain).
if [ -n "${SQLD_AUTH_JWT_KEY:-}" ] || [ -n "${SQLD_AUTH_JWT_KEY_FILE:-}" ]; then
  unset SQLD_HTTP_AUTH
  echo "railway-start: JWT authentication enabled"
elif [ -n "${SQLD_HTTP_AUTH:-}" ]; then
  echo "railway-start: SQLD_HTTP_AUTH authentication enabled"
elif [ -n "${SQLD_AUTH_TOKEN:-}" ]; then
  case "$SQLD_AUTH_TOKEN" in
    *[!A-Za-z0-9_-]*) echo "railway-start: SQLD_AUTH_TOKEN may only contain A-Z, a-z, 0-9, _ and -" >&2; exit 1 ;;
  esac
  if [ "${#SQLD_AUTH_TOKEN}" -lt 24 ]; then
    echo "railway-start: SQLD_AUTH_TOKEN must be at least 24 characters" >&2; exit 1
  fi
  export SQLD_HTTP_AUTH="basic:${SQLD_AUTH_TOKEN}"
  echo "railway-start: token authentication enabled"
elif [ "${SQLD_ALLOW_NO_AUTH:-false}" = "true" ]; then
  echo "railway-start: WARNING: authentication is disabled (SQLD_ALLOW_NO_AUTH=true)" >&2
else
  echo "railway-start: refusing to start without authentication. Set SQLD_AUTH_TOKEN (or SQLD_AUTH_JWT_KEY)." >&2
  exit 1
fi

# A fresh Railway volume is owned by root; let the sqld user write next to the database.
if [ "$(id -u)" = "0" ]; then
  case "$SQLD_DB_PATH" in
    /*) mkdir -p "$(dirname "$SQLD_DB_PATH")" && chown sqld:sqld "$(dirname "$SQLD_DB_PATH")" ;;
  esac
fi

exec /usr/local/bin/docker-wrapper.sh "$@"
